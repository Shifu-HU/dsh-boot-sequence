#!/usr/bin/env python3
"""Inline the subset fonts into build/fonts.css as data: URLs.

The plugin must not fetch anything at boot time, so the two faces travel as
base64 inside the stylesheet the Client module inserts.
"""
import base64
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
fonts = root / "build" / "fonts"

def b64(name):
    return base64.b64encode((fonts / name).read_bytes()).decode("ascii")

css = f"""/* generated by tools/build-fonts-css.py — do not edit */
@font-face {{
  font-family: "DSH Boot Mono";
  src: url(data:font/woff2;base64,{b64('fira-mono-ascii.woff2')}) format("woff2");
  font-weight: normal;
  font-style: normal;
  font-display: block;
}}
@font-face {{
  font-family: "DSH Boot Display";
  src: url(data:font/woff2;base64,{b64('united-sans-caps.woff2')}) format("woff2");
  font-weight: normal;
  font-style: normal;
  font-display: block;
}}
"""

out = root / "build" / "fonts.css"
out.write_text(css, encoding="utf-8")
print("wrote", out, len(css), "bytes")
